    internal static bool Allows(string path, string method, bool websocket)
    {
        if (path.Length > 4096 || path.Contains("..", StringComparison.Ordinal) || path.Contains('\\') || path.Any(char.IsControl) || path.Contains('%')) return false;
        if (websocket) return method == "GET" && path is "/ws/agent/" or "/ws/chat-voice/" or "/ws/terminals/" or "/ws/interactor/";
        if (path.StartsWith("/static/", StringComparison.Ordinal)) return method is "GET" or "HEAD";
        return method is "GET" or "HEAD" or "POST" or "PUT" or "PATCH" or "DELETE" && Routes.Any(pattern => pattern.IsMatch(path));
    }
